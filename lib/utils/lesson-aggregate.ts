/**
 * `lessons.content_md` у урока с шагами — производная проекция, а не авторский
 * текст (заход «шаги внутри урока», 23.08). Ученик читает `lesson_steps.content_md`
 * по одному шагу; колонку урока читают машины: FTS-триггер `lessons_search_vector_trg`,
 * грепы директив (`:::mock` в `mocks.ts`, `:::question` в `questions.ts`) и гварды
 * публикации.
 *
 * Поэтому проекция собирается ТОЛЬКО из того, что ментор действительно написал.
 * Прежняя сборка подставляла заголовком название шага (`## {title}`) — навигационную
 * подпись, которой нет ни в одном редактируемом поле содержимого: ошибиться в ней
 * можно (стёртая копия оставляет чужое название), а исправить в тексте урока — нельзя.
 */
export function buildLessonAggregate(steps: readonly { contentMd: string }[]): string {
  return steps
    .map((step) => step.contentMd.trim())
    .filter(Boolean)
    .join("\n\n");
}
