// Нижний док экрана: сколько пикселей у нижнего края уже занято контролом
// (spec 7.6/13, заход «Хвосты по тостам и высоте»).
//
// Находка ревью: отступ тостов был константой `bottom: 4.75rem` — высотой
// мобильной навигации. Но `BottomNav` монтируется только в
// `app/(student)/layout.tsx` и только `<768px`; в focused-зоне (сессия
// повторений, свободная тренировка, тест, онбординг) навигации нет, зато внизу
// может стоять ЛИПКАЯ панель оценок, а на странице курса — липкая CTA
// «Продолжить». Константа знала только про один из трёх контролов.
//
// DECISION (измерение, а не CSS-переменная от контрола): CSS-переменную нельзя
// передать вверх по дереву — док (`BottomNav`, панель оценок, CTA курса) лежит
// ГЛУБЖЕ вьюпорта тостов, который висит в корневом layout. Вариант «медиазапрос
// + `:has()`» вернул бы ту же константу-высоту, от которой мы уходим, а высота
// панели оценок зависит от содержимого (одна строка кнопок или две, подсказка
// клавиш на десктопе). Поэтому док измеряется: элемент помечает себя
// `data-bottom-dock`, наблюдатель пишет фактическую величину в `--bottom-dock`
// на `<html>`, а вьюпорт тостов её читает. Логика подсчёта — здесь, чистой
// функцией под тестами (jsdom в проекте нет).

/** Прямоугольник дока в координатах вьюпорта — то, что отдаёт getBoundingClientRect. */
export interface DockRect {
  top: number;
  height: number;
  width: number;
}

/** Зазор между плавающим элементом (тостом) и доком под ним. */
export const DOCK_GAP_PX = 16;

/** Док не может съесть больше половины экрана — иначе тосту негде жить. */
export const DOCK_MAX_SHARE = 0.5;

/**
 * Высота занятой полосы у нижнего края: `вьюпорт − верхняя граница самого
 * высокого дока`. Ноль, если внизу ничего мешающего нет.
 *
 * `floatHeight` — фактическая высота плавающего элемента, который надо
 * поднять (стек тостов; 0, когда тостов нет). Док учитывается, только если он
 * достаёт до полосы `зазор + floatHeight` у нижнего края, то есть если тост в
 * своём обычном положении действительно на него налез бы. Без этой проверки
 * тост уезжал бы на середину экрана всякий раз, когда липкая панель оценок
 * стоит по месту (короткий эталон — дека целиком помещается в экран, панель не
 * прилипает и тосту не мешает).
 *
 * Обратной связи нет: высота стека тостов не зависит от того, на какой высоте
 * он стоит, — значит один пересчёт всегда сходится.
 *
 * Считается именно от ВЕРХНЕЙ границы дока, а не по его высоте: так величина
 * уже включает и safe-area внутри дока (`BottomNav` носит
 * `pb-[env(safe-area-inset-bottom)]`), и зазор между доком и краем экрана.
 * Поэтому потребитель берёт `max(--bottom-dock, env(safe-area-inset-bottom))`,
 * а не сумму — иначе инсет считался бы дважды.
 */
export function bottomDockOffset(
  rects: readonly DockRect[],
  viewportHeight: number,
  floatHeight = 0,
): number {
  if (viewportHeight <= 0) return 0;
  const band = DOCK_GAP_PX + Math.max(0, floatHeight);
  let offset = 0;
  for (const rect of rects) {
    // 0×0 — элемент скрыт (`md:hidden` на BottomNav даёт display:none).
    if (rect.width <= 0 || rect.height <= 0) continue;
    if (rect.top + rect.height < viewportHeight - band) continue;
    const occupied = Math.min(viewportHeight - rect.top, viewportHeight * DOCK_MAX_SHARE);
    if (occupied > offset) offset = occupied;
  }
  return Math.max(0, Math.round(offset));
}
