// Жест переключения карточки в сессии тренажёра (spec 7.6/13, заход
// «Мобильный тренажёр и тосты»).
//
// Находка владельца: на телефоне длинный вопрос/эталон не пролистывался —
// попытка проскроллить содержимое улетала в оценку и карточка перелистывалась.
// Прежняя схема сравнивала только начало и конец касания и отбрасывала жест
// лишь по факту изменившегося `window.scrollY`. Этого мало сразу в трёх местах:
//
//   1. вертикальный свайп ВНИЗ был отдельной оценкой («сомневаюсь»), то есть
//      скролл и оценка спорили за один и тот же жест;
//   2. упёршийся скролл (низ страницы, верх страницы, iOS-rubber-band) не меняет
//      scrollY вовсе — жест доезжал до оценки как «настоящий» свайп;
//   3. горизонтальная прокрутка блока кода / KaTeX / широкой таблицы внутри
//      эталона — тоже свайп по всем прежним признакам.
//
// Новое правило: переключение — ТОЛЬКО горизонтальный свайп с явным порогом и
// доминирующей осью, всё остальное отдаётся скроллу. Логика чистая (без DOM):
// вызывающая дека собирает контекст из событий, а решение принимается здесь и
// покрывается тестами — jsdom в проекте нет.
//
// DECISION: свайп «вниз = сомневаюсь» из 7.6 на мобильном отменён. Отличить его
// от прокрутки длинного контента надёжно нельзя ни на одном из движков, а
// устройства учеников неизвестны. Оценка «Сомневаюсь» остаётся кнопкой (зона
// ≥44px, панель липкая) и клавишей 2 — потери функциональности нет.

/** Порог свайпа: короткие движения — это удержание/скролл, а не переключение. */
export const SWIPE_MIN_DISTANCE_PX = 72;

/** Во сколько раз горизонталь должна перевесить вертикаль, чтобы это был свайп. */
export const SWIPE_AXIS_RATIO = 1.6;

/** С какого смещения по вертикали жест считается намерением скроллить. */
export const SCROLL_INTENT_PX = 12;

export type DeckSwipe = "again" | "good" | null;

export interface SwipeContext {
  /** Смещение пальца за жест, px. */
  dx: number;
  dy: number;
  /**
   * В любой момент жеста вертикаль перевешивала — человек скроллит.
   * Считается по touchmove, а не по конечной точке: палец мог вернуться назад.
   */
  verticalIntent: boolean;
  /** Касание началось внутри блока с горизонтальной прокруткой (код, KaTeX, таблица). */
  insideScrollableX: boolean;
  /** За время жеста что-то действительно проскроллилось (страница или тело карточки). */
  scrolled: boolean;
}

/** Намерение скроллить: вертикаль ушла заметно дальше горизонтали. */
export function isVerticalIntent(dx: number, dy: number): boolean {
  return Math.abs(dy) >= SCROLL_INTENT_PX && Math.abs(dy) > Math.abs(dx);
}

/**
 * Оценка по свайпу или `null`, если жест принадлежит скроллу.
 *
 * Порядок проверок — от самого дешёвого отказа к самому дорогому: любой признак
 * скролла закрывает вопрос сразу, и только «чистая» горизонталь доходит до
 * оценки. Вертикальных исходов у функции нет по построению.
 */
export function resolveSwipe(context: SwipeContext): DeckSwipe {
  if (context.insideScrollableX) return null;
  if (context.verticalIntent) return null;
  if (context.scrolled) return null;
  const { dx, dy } = context;
  if (Math.abs(dx) < SWIPE_MIN_DISTANCE_PX) return null;
  if (Math.abs(dx) < Math.abs(dy) * SWIPE_AXIS_RATIO) return null;
  return dx < 0 ? "again" : "good";
}
