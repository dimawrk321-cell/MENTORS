export async function ensureWelcomeCourse(db: Db, dryRun = false): Promise<string> {
  const existing = await db.course.findUnique({
    where: { slug: COURSE_SLUG },
    include: { modules: { include: { lessons: true } } },
  });

  if (existing) {
    const lessonCount = existing.modules.reduce((n, m) => n + m.lessons.length, 0);
    console.log(
      `Курс «${COURSE_TITLE}» уже существует (${existing.status}, ${lessonCount} уроков) — создание пропущено.`,
    );
    return existing.id;
  }

  console.log(
    `${dryRun ? "[dry-run] " : ""}Создаю курс «${COURSE_TITLE}» (slug ${COURSE_SLUG}, gating free, статус draft), ` +
      `1 модуль, ${LESSONS.length} уроков (published).`,
  );
  if (dryRun) return "welcome-dry-run-id";

  const now = new Date();
  const course = await db.course.create({
    data: {
      slug: COURSE_SLUG,
      title: COURSE_TITLE,
      description: COURSE_DESCRIPTION,
      order: 0,
      gating: "free",
      status: "draft",
      modules: {
        create: {
          title: MODULE_TITLE,
          order: 0,
          status: "published",
          lessons: {
            create: LESSONS.map((l, index) => ({
              slug: l.slug,
              title: l.title,
              order: index,
              status: "published" as const,
              difficulty: "intro" as const,
              isOptional: false,
              contentMd: l.contentMd,
              readingMinutes: computeReadingMinutes(l.contentMd),
              publishedAt: now,
            })),
          },
        },
      },
    },
  });
  return course.id;
}

/**
 * Дозаливка недостающих уроков вводного курса (заход B.2, блок 2.3).
 *
 * `ensureWelcomeCourse` существующий курс НЕ ТРОГАЕТ — это инвариант: правки
 * ментора затирать нельзя. Но новый урок «Правила игры» нужно донести и до тех
 * баз, где курс уже создан. Механизм: **сверка по slug внутри модуля курса**.
 *   • урок с таким slug уже есть — пропускаем, содержимое НЕ обновляем
 *     (даже если ментор переписал его целиком — это его текст);
 *   • урока нет — создаём в конце, `order = max(order) + 1`.
 * Повторный прогон после первого — ноль изменений; порядок и статусы соседей не
 * трогаются вовсе.
 *
 * ОГОВОРКА: если урок вводного курса удалили НАМЕРЕННО, следующий прогон
 * вернёт его обратно — отличить «удалили» от «ещё не создавали» по slug
 * невозможно. Поэтому дозаливка вызывается только из явного CLI-скрипта
 * (`scripts/seed-welcome-course.ts`), то есть руками оператора, а не из общего
 * сида: там курс либо создаётся целиком, либо уже полон.
 */
export async function addMissingWelcomeLessons(
  db: Db,
  dryRun = false,
): Promise<{ added: string[]; skipped: number }> {
  const course = await db.course.findUnique({
    where: { slug: COURSE_SLUG },
    include: { modules: { orderBy: { order: "asc" }, include: { lessons: true } } },
  });
  const target = course?.modules[0];
  if (!course || !target) return { added: [], skipped: 0 };

  const bySlug = new Map(target.lessons.map((lesson) => [lesson.slug, lesson]));
  const missing = LESSONS.filter((seed) => !bySlug.has(seed.slug));
  if (missing.length === 0) {
    console.log(`  уроки: все ${LESSONS.length} на месте — дозаливать нечего.`);
    return { added: [], skipped: target.lessons.length };
  }

  let nextOrder = target.lessons.reduce((max, lesson) => Math.max(max, lesson.order), -1) + 1;
  const now = new Date();
  for (const seed of missing) {
    console.log(
      `  ${dryRun ? "[dry-run] " : ""}добавляю урок «${seed.title}» (slug ${seed.slug}, order ${nextOrder}).`,
    );
    if (!dryRun) {
      await db.lesson.create({
        data: {
          moduleId: target.id,
          slug: seed.slug,
          title: seed.title,
          order: nextOrder,
          status: "published",
          difficulty: "intro",
          isOptional: false,
          contentMd: seed.contentMd,
          readingMinutes: computeReadingMinutes(seed.contentMd),
          publishedAt: now,
        },
      });
    }
    nextOrder += 1;
  }
  return { added: missing.map((seed) => seed.slug), skipped: target.lessons.length };
}

/** Prepends the welcome course id to every track's course_ids (idempotent). */
export async function pinWelcomeFirstInTracks(
  db: Db,
  welcomeId: string,
  dryRun = false,
): Promise<void> {
  const tracks = await db.trackDef.findMany();
  for (const track of tracks) {
    const current = Array.isArray(track.courseIds) ? (track.courseIds as string[]) : [];
    if (current[0] === welcomeId) {
      console.log(`  ${track.key}: уже первый — пропуск.`);
      continue;
    }
    const next = [welcomeId, ...current.filter((id) => id !== welcomeId)];
    console.log(
      `  ${track.key}: ставлю welcome первым (${current.length} → ${next.length} курсов)` +
        `${dryRun ? " [dry-run]" : ""}.`,
    );
    if (!dryRun) {
      await db.trackDef.update({
        where: { key: track.key as Track },
        data: { courseIds: next },
      });
    }
  }
}
