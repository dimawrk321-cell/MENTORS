-- Заход C.5: снятие мёртвой ветки встраивания записей.
--
-- Колонка хранила embed-URL для iframe-плеера поверх записи. Встроить запись
-- Я.Диска во фрейм чужого домена запрещает САМ ИСТОЧНИК: публичная страница
-- отдаёт `frame-ancestors webvisor.com *.webvisor.com …`, а `/embed/<ключ>` —
-- 302 на паспорт и `X-Frame-Options: SAMEORIGIN`. Послаблением нашей CSP это не
-- лечится, поэтому ветка не могла сработать и не срабатывала.
--
-- Данных не теряется — проверено на стенде НЕПОСРЕДСТВЕННО перед применением
-- (принцип 0.10: проверяется результат, а не намерение):
--   select count(*) total, count(embed_url) with_embed from recordings;
--   →  total = 1, with_embed = 0
-- Единственная запись опубликована, её url — ссылка вида /d/ (папка Диска).
--
-- Необратимость: возврат колонки — это `ADD COLUMN "embed_url" TEXT` без
-- восстановления данных, восстанавливать нечего. Плеер вернётся с переездом на
-- видеохостинг с подписанными URL (V1 раздела 16) — другой колонкой.
ALTER TABLE "recordings" DROP COLUMN "embed_url";
