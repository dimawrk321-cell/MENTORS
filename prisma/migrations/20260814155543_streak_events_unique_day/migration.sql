-- Заход A.2: уникальность события стрика на (пользователь, день, вид).
--
-- До строчной блокировки в countStreakDay параллельные вызовы писали два
-- события `counted` за один день (24 прогона из 25) — останавливать было
-- нечему. Блокировка это чинит; индекс делает повтор невозможным на уровне БД.
--
-- Дубли перед применением проверены на стенде: 0 групп (user_id, date, kind)
-- с count > 1 при 75 событиях.
CREATE UNIQUE INDEX "streak_events_user_id_date_kind_key" ON "streak_events"("user_id", "date", "kind");
